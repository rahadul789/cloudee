export function useOwnerTranslation() {
  const language = useOwnerLanguageStore((state) => state.language);
  const setLanguage = useOwnerLanguageStore((state) => state.setLanguage);

  return useMemo(
    () => ({
      language,
      setLanguage,
      t: (key: TranslationKey) => translateOwner(language, key),
    }),
    [language, setLanguage],
  );
}
